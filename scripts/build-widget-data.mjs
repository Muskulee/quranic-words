#!/usr/bin/env node
// Writes the compact word pool the iOS widget compiles in (targets/widget/WidgetWords.swift),
// so the widget never needs the app or the network.
// Keep WIDGET_POOL in sync with wordOfTheDay() in src/lib/words.ts.
import { readFile, writeFile } from 'node:fs/promises';

const WIDGET_POOL = 365;
const { words } = JSON.parse(await readFile(new URL('../src/data/words.json', import.meta.url), 'utf8'));
const pool = words.slice(0, WIDGET_POOL).map((w) => ({ ar: w.ar, tr: w.tr, en: w.meaning.en, ur: w.meaning.ur, id: w.meaning.id }));
const json = JSON.stringify(pool);
if (json.includes('"#')) throw new Error('word data would break the Swift raw string');
await writeFile(
  new URL('../targets/widget/WidgetWords.swift', import.meta.url),
  `// Generated by scripts/build-widget-data.mjs. Do not edit.\nlet widgetWordsJSON = #"${json}"#\n`
);
console.log(`wrote ${pool.length} widget words`);
